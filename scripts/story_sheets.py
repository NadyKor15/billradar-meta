"""Who sent each sheet of the example, its kind and first codes, for the Muse Spark arc and the Muse Wonder cards:

  python scripts/story_sheets.py

Reads runs/example/case.json and writes billradar/web/templates/_story_sheets.html. Only what the run read, nothing typed by hand."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KIND = {"eob": "Explanation of Benefits", "hospital_statement": "Statement", "itemized_bill": "Itemized Bill", "other": ""}
EOB_PAGES = {"S3", "S6"}  # second pages of an insurer's statement: they carry no sender of their own

rows = {}
for d in json.loads((ROOT / "runs" / "example" / "case.json").read_text())["documents"]:
    org = (d.get("provider") or "").removeprefix("300_")
    if d["kind"] == "eob" or d["doc_id"] in EOB_PAGES:
        org = "Harborlight Health"
    org = org.split(" - ")[0].removesuffix(", LLC")
    rows[d["doc_id"]] = {"org": org.title() if org.isupper() else org, "kind": KIND.get(d["kind"], ""),
                         "codes": [x["code"] for x in d.get("lines", []) if x.get("code")][:3]}
out = ROOT / "billradar" / "web" / "templates" / "_story_sheets.html"
out.write_text("{# Generated by scripts/story_sheets.py from the example run. #}\n{% set SHEETS = " + json.dumps(rows) + " %}\n")
print(len(rows), "sheets and files")
